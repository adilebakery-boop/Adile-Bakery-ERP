function generateFilename(reportType, branchName, filters, dateOrMonth, monthName, year, weekStartDate, weekEndDate, monthStartDate, monthEndDate) {
  const branchSlug = branchName ? branchName.toLowerCase().replace(/\s+/g, '-') : 'all-branches';

  let filename;
  if (reportType === 'daily') {
    filename = `daily-report-${dateOrMonth}.xlsx`;
  } else if (reportType === 'weekly') {
    filename = `weekly-report-${weekStartDate}.xlsx`;
  } else if (reportType === 'monthly') {
    filename = `${monthName.toLowerCase()}-monthly-report-${year}-${monthStartDate}-to-${monthEndDate}.xlsx`;
  } else if (reportType === 'yearly') {
    filename = `yearly-report-${year}.xlsx`;
  } else {
    filename = `${dateOrMonth}-${reportType}-report-${branchSlug}.xlsx`;
  }

  if (filters.category) {
    filename = filename.replace('.xlsx', `-${filters.category.toLowerCase()}.xlsx`);
  }
  if (filters.product) {
    const productSlug = filters.product.toLowerCase().replace(/\s+/g, '-');
    filename = filename.replace('.xlsx', `-${productSlug}.xlsx`);
  }

  return filename;
}

